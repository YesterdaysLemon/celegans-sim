let mXY = 0, mV = 0, mGate = 0;
prev = 0;
for (const f of mc.frames) {
  E.step(w4, f.step - prev);
  prev = f.step;
  const nx = F64().subarray(E.ptrNodesX(w4) >> 3, (E.ptrNodesX(w4) >> 3) + f.x.length);
  const ny = F64().subarray(E.ptrNodesY(w4) >> 3, (E.ptrNodesY(w4) >> 3) + f.y.length);
  const vv = F64().subarray(E.ptrV(w4) >> 3, (E.ptrV(w4) >> 3) + f.V.length);
  for (let i = 0; i < f.x.length; i++)
    mXY = Math.max(mXY, Math.abs(nx[i] - f.x[i]), Math.abs(ny[i] - f.y[i]));
  for (let i = 0; i < f.V.length; i++) mV = Math.max(mV, Math.abs(vv[i] - f.V[i]));
  if (E.getGateForward(w4) !== f.gate) mGate++;
}
/* And the case has to be *different* from the one with the channel shut, or it is another
 * comparison over a term that never moved. Same seed, same plate, coefficient 0 vs 0.30. */
E.resetWorld(); E.clearWorms(); E.setNoise(0);
E.addFood(-6.0, 4.0, 5.0, 1.0, 1.0, 9.0);
E.addRepellent(7.0, -3.0, 0.9, 5.0);
E.addFood(0.0, 0.0, 3.0, 1.0, 0.6, 6.0);
const wOff = E.createWorm(0, 0.0, 0.0, 0.0);
E.step(wOff, mc.steps);
const offV = Array.from(F64().subarray(E.ptrV(wOff) >> 3, (E.ptrV(wOff) >> 3) + 302));
const lastV = mc.frames[mc.frames.length - 1].V;
let mod1Effect = 0;
