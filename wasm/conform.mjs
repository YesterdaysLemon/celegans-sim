const mc = ref.mod1;
if (!mc) { console.error('reference has no `mod1` case -- regenerate it'); process.exit(1); }
E.resetWorld();
E.clearWorms();
E.setNoise(0);
E.addFood(-6.0, 4.0, 5.0, 1.0, 1.0, 9.0);
E.addRepellent(7.0, -3.0, 0.9, 5.0);
E.addFood(0.0, 0.0, 3.0, 1.0, 0.6, 6.0);
const w4 = E.createWorm(0, 0.0, 0.0, 0.0);
